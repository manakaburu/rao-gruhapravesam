import { strict as assert } from 'node:assert'
import { readFile, stat } from 'node:fs/promises'
const file = async path => readFile(new URL('../'+path, import.meta.url), 'utf8')
const stage = await file('src/components/CinematicStage.tsx')
const css = await file('src/styles/invitation.css')
const audio = await file('src/components/InvitationMusic.tsx')
const leaves = await file('src/components/FallingLeaves.tsx')
assert(stage.includes('story-is-active') && stage.includes('trigger: track'), 'CSS-sticky storytelling not active')
assert(stage.includes('ignoreMobileResize: true'), 'Mobile toolbar protection missing')
assert(!stage.includes('sections.every(section => section.offsetHeight'), 'Height-based story mode switch returned')
assert(!stage.includes('pin: true'), 'Jump-prone GSAP pin spacer returned')
assert(css.includes('position:sticky') && css.includes('100svh'), 'Stable story stage CSS missing')
assert(css.includes('@keyframes rao-bell-sway') && css.includes('@keyframes rao-vine-sway'), 'Subtle ambient movement missing')
const x=[...leaves.matchAll(/x:\s*(\d+)/g)].map(m=>Number(m[1]))
assert(x.length >= 6 && x.every(v=>v <= 10 || v >= 90), 'Falling foliage must remain at the corners')
assert(audio.includes('achyutam-keshavam-user-upload.mp3'), 'Uploaded local MP3 integration missing')
assert(audio.includes('await sound.play()'), 'Autoplay attempt and click fallback missing')
const local = await stat(new URL('../public/audio/achyutam-keshavam-user-upload.mp3',import.meta.url))
assert(local.size>100000,'Bundled user-supplied audio missing')
console.log('Sticky cinematic on touch/desktop, corner petals, bell/vine sway and local music PASS')
